using System.Globalization;
using System.Text;

namespace PrintDeck.Infrastructure.Virtual;

/// <summary>
/// The virtual printer's SD card: a few files in memory, M20–M30 and M524 the way Marlin answers them.
/// Printing from the card only advances the file position over time; nothing moves.
/// </summary>
public sealed partial class VirtualPrinterTransport
{
	private const double _sdBytesPerSecond = 600;

	private readonly Lock _sd = new();
	private readonly Dictionary<string, SdEntry> _sdFiles = new(StringComparer.OrdinalIgnoreCase)
	{
		["CALCUBE.GCO"] = new("calibration-cube.gcode", DemoGcode(40)),
		["BENCHY~1.GCO"] = new("benchy 0.2mm PLA.gcode", DemoGcode(120))
	};
	private bool _sdMounted = true;
	private string? _sdSelected;
	private long _sdPosition;
	private bool _sdPrinting;
	private TimeSpan _sdAutoReport = TimeSpan.Zero;
	private DateTimeOffset _sdLastReport;
	private string? _sdWriting;
	private StringBuilder? _sdWriteBuffer;

	private sealed record SdEntry(string? LongName, string Content)
	{
		public long Size => Encoding.UTF8.GetByteCount(Content);
	}

	/// <summary>Files on the virtual card by 8.3 name, with their content.</summary>
	public IReadOnlyDictionary<string, string> SdFiles
	{
		get { lock (_sd) return _sdFiles.ToDictionary(f => f.Key, f => f.Value.Content); }
	}

	private static string DemoGcode(int layers)
	{
		StringBuilder gcode = new("; generated by PrintDeck's virtual printer\nG28\nG90\n");
		for (int layer = 1; layer <= layers; layer++)
		{
			gcode.Append(CultureInfo.InvariantCulture, $";LAYER:{layer}\nG1 Z{layer * 0.2:0.0} F600\n");
			for (int side = 0; side < 4; side++)
				gcode.Append(CultureInfo.InvariantCulture, $"G1 X{(side is 1 or 2 ? 120 : 100)} Y{(side >= 2 ? 120 : 100)} E{layer * 0.4 + side * 0.1:0.00} F1800\n");
		}
		return gcode.Append("M104 S0\nM140 S0\n").ToString();
	}

	/// <summary>While <c>M28</c> is open every line goes into the file until <c>M29</c>. True when the line was taken.</summary>
	private bool WriteToSd(string command)
	{
		lock (_sd)
		{
			if (_sdWriting is null) return false;
			if (command.StartsWith("M29", StringComparison.OrdinalIgnoreCase))
			{
				_sdFiles[_sdWriting] = new SdEntry(null, _sdWriteBuffer!.ToString());
				_sdWriting = null;
				_sdWriteBuffer = null;
				Emit("Done saving file.");
			}
			else _sdWriteBuffer!.Append(command).Append('\n');
		}
		Emit("ok");
		return true;
	}

	/// <summary>Handles an SD card command; false when <paramref name="code"/> is not one.</summary>
	private bool ExecuteSd(string code, string[] parts, Func<char, double?> arg)
	{
		string name = parts.Length > 1 ? parts[1] : "";
		lock (_sd)
		{
			switch (code)
			{
				case "M20":
					if (!_sdMounted) { Emit("echo:No media"); break; }
					bool longNames = parts.Skip(1).Any(p => p.Equals("L", StringComparison.OrdinalIgnoreCase));
					Emit("Begin file list");
					foreach ((string path, SdEntry file) in _sdFiles.OrderBy(f => f.Key, StringComparer.Ordinal))
						Emit(longNames ? $"{path} {file.Size} {file.LongName ?? path}" : $"{path} {file.Size}");
					Emit("End file list");
					break;
				case "M21":
					_sdMounted = true;
					Emit("echo:SD card ok");
					break;
				case "M22":
					if (!_sdPrinting) _sdMounted = false;
					Emit("echo:SD card released");
					break;
				case "M23":
					if (_sdMounted && _sdFiles.TryGetValue(name, out SdEntry? selected))
					{
						_sdSelected = name.ToUpperInvariant();
						_sdPosition = 0;
						Emit($"echo:Now fresh file: {_sdSelected}");
						Emit($"File opened: {_sdSelected} Size: {selected.Size}");
						Emit("File selected");
					}
					else Emit($"echo:open failed, File: {name}.");
					break;
				case "M24":
					if (_sdSelected is not null) _sdPrinting = true;
					break;
				case "M25":
					_sdPrinting = false;
					break;
				case "M26":
					if (_sdSelected is not null && arg('S') is { } position) _sdPosition = (long) position;
					break;
				case "M27":
					if (arg('S') is { } seconds) _sdAutoReport = TimeSpan.FromSeconds(seconds);
					else Emit(SdProgress());
					break;
				case "M28":
					if (!_sdMounted || name.Length == 0) { Emit($"echo:open failed, File: {name}."); break; }
					_sdWriting = name.ToUpperInvariant();
					_sdWriteBuffer = new StringBuilder();
					Emit($"Writing to file: {_sdWriting}");
					break;
				case "M30":
					Emit(_sdFiles.Remove(name) ? $"File deleted:{name}" : $"Deletion failed, File: {name}.");
					break;
				case "M524":
					_sdPrinting = false;
					_sdSelected = null;
					break;
				default:
					return false;
			}
		}
		return true;
	}

	/// <summary>Called by the physics loop: advances an SD print and auto-reports progress.</summary>
	private void TickSd(TimeSpan elapsed)
	{
		lock (_sd)
		{
			if (_sdPrinting && _sdSelected is not null && _sdFiles.TryGetValue(_sdSelected, out SdEntry? file))
			{
				_sdPosition = Math.Min(file.Size, _sdPosition + (long) (_sdBytesPerSecond * speedFactor * elapsed.TotalSeconds));
				if (_sdPosition >= file.Size)
				{
					Emit(SdProgress());
					_sdPrinting = false;
					_sdSelected = null;
					Emit("Done printing file");
					return;
				}
			}

			DateTimeOffset now = time.GetUtcNow();
			if (_sdAutoReport > TimeSpan.Zero && _sdSelected is not null && now - _sdLastReport >= _sdAutoReport)
			{
				Emit(SdProgress());
				_sdLastReport = now;
			}
		}
	}

	private string SdProgress() =>
		_sdSelected is not null && _sdFiles.TryGetValue(_sdSelected, out SdEntry? file)
			? $"SD printing byte {_sdPosition}/{file.Size}"
			: "Not SD printing";
}
