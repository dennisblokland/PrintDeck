using System.Globalization;
using System.Text.RegularExpressions;

using PrintDeck.Domain.Files;

namespace PrintDeck.Application.Files;

/// <summary>Reads slicer metadata (Cura, PrusaSlicer, OrcaSlicer/Bambu) and falls back to simulating moves.</summary>
public static partial class GcodeAnalyzer
{
	[GeneratedRegex(@"(\d+)\s*([dhms])")]
	private static partial Regex DurationPart();

	public static async Task<GcodeAnalysis> AnalyzeAsync(Stream stream, CancellationToken ct)
	{
		using StreamReader reader = new(stream);
		MoveSimulator sim = new();
		TimeSpan? time = null;
		double? filament = null;
		int? layers = null;
		string? slicer = null;
		int layerMarkers = 0;
		long commands = 0;

		while (await reader.ReadLineAsync(ct) is { } raw)
		{
			string line = raw.Trim();
			if (line.Length == 0) continue;

			if (line[0] == ';')
			{
				string c = line.TrimStart(';', ' ');
				if (slicer is null && c.StartsWith("generated by ", StringComparison.OrdinalIgnoreCase))
					slicer = c[13..].Split(' ')[0];
				else if (slicer is null && c.StartsWith("Generated with ", StringComparison.OrdinalIgnoreCase))
					slicer = c[15..].Split(' ')[0];
				else if (c.StartsWith("TIME:", StringComparison.Ordinal) && double.TryParse(c[5..], CultureInfo.InvariantCulture, out double secs))
					time ??= TimeSpan.FromSeconds(secs);
				else if (c.Contains("total estimated time:", StringComparison.OrdinalIgnoreCase))
					time = ParseDuration(c[(c.IndexOf("total estimated time:", StringComparison.OrdinalIgnoreCase) + 21)..]) ?? time;
				else if (c.StartsWith("estimated printing time (normal mode)", StringComparison.OrdinalIgnoreCase))
					time ??= ParseDuration(c[(c.IndexOf('=') + 1)..]);
				else if (c.StartsWith("filament used [mm]", StringComparison.OrdinalIgnoreCase))
					filament ??= SumNumbers(c[(c.IndexOf('=') + 1)..]);
				else if (c.StartsWith("Filament used:", StringComparison.OrdinalIgnoreCase) && c.EndsWith('m'))
					filament ??= SumNumbers(c[14..].TrimEnd('m')) * 1000;
				else if (c.StartsWith("LAYER_COUNT:", StringComparison.Ordinal) && int.TryParse(c[12..], out int lc))
					layers ??= lc;
				else if (c.StartsWith("total layer number:", StringComparison.OrdinalIgnoreCase) && int.TryParse(c[19..].Trim(), out int tl))
					layers ??= tl;
				else if (c.StartsWith("LAYER_CHANGE", StringComparison.Ordinal) || c.StartsWith("LAYER:", StringComparison.Ordinal))
					layerMarkers++;
				continue;
			}

			commands++;
			int semicolon = line.IndexOf(';');
			sim.Apply(semicolon >= 0 ? line[..semicolon] : line);
		}

		return new GcodeAnalysis(
			time ?? (sim.Seconds > 0 ? TimeSpan.FromSeconds(sim.Seconds) : null),
			filament ?? (sim.Extruded > 0 ? sim.Extruded : null),
			layers ?? (layerMarkers > 0 ? layerMarkers : null),
			commands,
			slicer);
	}

	internal static TimeSpan? ParseDuration(string text)
	{
		TimeSpan total = TimeSpan.Zero;
		bool any = false;
		foreach (Match m in DurationPart().Matches(text))
		{
			any = true;
			int v = int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture);
			total += m.Groups[2].Value switch
			{
				"d" => TimeSpan.FromDays(v),
				"h" => TimeSpan.FromHours(v),
				"m" => TimeSpan.FromMinutes(v),
				_ => TimeSpan.FromSeconds(v)
			};
		}
		return any ? total : null;
	}

	private static double? SumNumbers(string text)
	{
		double sum = 0;
		bool any = false;
		foreach (string part in text.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
			if (double.TryParse(part, CultureInfo.InvariantCulture, out double v)) { sum += v; any = true; }
		return any ? sum : null;
	}
}
