using System.Text;

using PrintDeck.Application.Files.Thumbnails;
using PrintDeck.Application.Tests.TestDoubles;
using PrintDeck.Domain.Files;

using static PrintDeck.Application.Tests.TestDoubles.ThumbnailSamples;

namespace PrintDeck.Application.Tests.Files.Thumbnails;

public class GcodeThumbnailReaderTests
{
	private const string Header = "; generated by OrcaSlicer 2.3.0 on 2026-11-17 at 10:00:00\n;\n";
	private const string Body = "G28\nG1 Z0.2 F600\nG1 X10 Y10 E1\n";

	private static Task<GcodeThumbnail?> Read(string gcode) =>
		GcodeThumbnailReader.ReadAsync(new MemoryStream(Encoding.UTF8.GetBytes(gcode)), TestContext.Current.CancellationToken);

	[Fact]
	public async Task Reads_a_png_thumbnail()
	{
		byte[] png = Png(160, 120);

		GcodeThumbnail? t = await Read(Header + Block("thumbnail", 160, 120, png) + Body);

		Assert.NotNull(t);
		Assert.Equal((160, 120, GcodeThumbnail.Png), (t.Width, t.Height, t.ContentType));
		Assert.Equal(png, t.Data);
	}

	[Fact]
	public async Task Reads_explicit_png_and_jpg_blocks()
	{
		Assert.Equal(GcodeThumbnail.Png, (await Read(Block("thumbnail_PNG", 32, 24, Png(32, 24)) + Body))?.ContentType);

		GcodeThumbnail? jpg = await Read(Block("thumbnail_JPG", 300, 200, Jpeg(300, 200)) + Body);
		Assert.Equal((300, 200, GcodeThumbnail.Jpeg), (jpg?.Width, jpg?.Height, jpg?.ContentType));
	}

	[Fact]
	public async Task Picks_the_largest_thumbnail()
	{
		string gcode = Header
			+ Block("thumbnail", 16, 16, Png(16, 16))
			+ Block("thumbnail", 220, 124, Png(220, 124))
			+ Block("thumbnail", 48, 48, Png(48, 48))
			+ Body;

		GcodeThumbnail? t = await Read(gcode);

		Assert.Equal((220, 124), (t?.Width, t?.Height));
	}

	[Fact]
	public async Task Turns_qoi_into_png()
	{
		RgbaImage image = Image(4, 3);

		GcodeThumbnail? t = await Read(Block("thumbnail_QOI", 4, 3, Qoi(image)) + Body);

		Assert.NotNull(t);
		Assert.Equal((4, 3, GcodeThumbnail.Png), (t.Width, t.Height, t.ContentType));
		Assert.Equal(PngEncoder.Encode(image), t.Data);
	}

	[Fact]
	public async Task Prefers_png_over_qoi_of_the_same_size()
	{
		byte[] png = Png(16, 16);

		GcodeThumbnail? t = await Read(Block("thumbnail", 16, 16, png) + Block("thumbnail_QOI", 16, 16, Qoi(Image(16, 16))) + Body);

		Assert.Equal(png, t?.Data);
	}

	[Fact]
	public async Task Skips_blocks_that_are_not_what_they_claim()
	{
		string gcode = Block("thumbnail", 16, 16, Encoding.ASCII.GetBytes("not a picture"))
			+ "; thumbnail begin 16x16 8\n; @@@@####\n; thumbnail end\n"
			+ Block("thumbnail_QOI", 16, 16, Png(16, 16))
			+ Body;

		Assert.Null(await Read(gcode));
	}

	[Fact]
	public async Task Ignores_an_unfinished_block()
	{
		string gcode = "; thumbnail begin 16x16 100\n; iVBORw0KGgo\nG28\n; thumbnail end\n" + Body;

		Assert.Null(await Read(gcode));
	}

	[Fact]
	public async Task Only_looks_in_the_header()
	{
		string commands = string.Concat(Enumerable.Repeat("G1 X1\n", 50));

		Assert.Null(await Read(Header + commands + Block("thumbnail", 16, 16, Png(16, 16))));
	}

	[Fact]
	public async Task Returns_null_without_thumbnails()
	{
		Assert.Null(await Read(Header + Body));
		Assert.Null(await Read(""));
	}
}
