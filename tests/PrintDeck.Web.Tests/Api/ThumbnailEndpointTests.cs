using System.Net;
using System.Text;

using PrintDeck.Application.Files.Thumbnails;

namespace PrintDeck.Web.Tests.Api;

public class ThumbnailEndpointTests(PrintDeckWebFactory app) : IClassFixture<PrintDeckWebFactory>
{
	private readonly HttpClient _client = app.CreateClient();
	private static CancellationToken Ct => TestContext.Current.CancellationToken;

	private static readonly byte[] _png = PngEncoder.Encode(new RgbaImage(2, 1, [255, 0, 0, 255, 0, 0, 255, 255]));

	private static string WithThumbnail(byte[] png)
	{
		string base64 = Convert.ToBase64String(png);
		return $"; generated by OrcaSlicer 2.3.0\n; thumbnail begin 2x1 {base64.Length}\n; {base64}\n; thumbnail end\nG28\nG1 X10\n";
	}

	private async Task Upload(string name, string gcode)
	{
		HttpRequestMessage request = new(HttpMethod.Post, "/api/files/local");
		request.Headers.Add("X-Api-Key", await app.ApiKeyAsync());
		request.Content = new MultipartFormDataContent { { new ByteArrayContent(Encoding.UTF8.GetBytes(gcode)), "file", name } };
		(await _client.SendAsync(request, Ct)).EnsureSuccessStatusCode();
	}

	private async Task<HttpResponseMessage> Get(string url, string? ifNoneMatch = null)
	{
		HttpRequestMessage request = new(HttpMethod.Get, url);
		request.Headers.Add("X-Api-Key", await app.ApiKeyAsync());
		if (ifNoneMatch is not null) request.Headers.TryAddWithoutValidation("If-None-Match", ifNoneMatch);
		return await _client.SendAsync(request, Ct);
	}

	[Fact]
	public async Task Needs_a_signed_in_user_or_the_api_key()
	{
		HttpResponseMessage r = await _client.GetAsync("/thumbnail/missing.gcode", Ct);
		Assert.Equal(HttpStatusCode.Unauthorized, r.StatusCode);
	}

	[Fact]
	public async Task Serves_the_thumbnail_of_an_upload()
	{
		await Upload("thumb-orca.gcode", WithThumbnail(_png));

		HttpResponseMessage r = await Get("/thumbnail/thumb-orca.gcode");

		Assert.Equal(HttpStatusCode.OK, r.StatusCode);
		Assert.Equal("image/png", r.Content.Headers.ContentType?.MediaType);
		Assert.Equal(_png, await r.Content.ReadAsByteArrayAsync(Ct));
	}

	[Fact]
	public async Task Answers_not_modified_for_the_same_upload()
	{
		await Upload("thumb-cached.gcode", WithThumbnail(_png));
		string etag = (await Get("/thumbnail/thumb-cached.gcode")).Headers.ETag!.Tag;

		HttpResponseMessage r = await Get("/thumbnail/thumb-cached.gcode", etag);

		Assert.Equal(HttpStatusCode.NotModified, r.StatusCode);
	}

	[Fact]
	public async Task Files_without_a_thumbnail_are_not_found()
	{
		await Upload("thumb-plain.gcode", "G28\n");

		Assert.Equal(HttpStatusCode.NotFound, (await Get("/thumbnail/thumb-plain.gcode")).StatusCode);
		Assert.Equal(HttpStatusCode.NotFound, (await Get("/thumbnail/missing.gcode")).StatusCode);
	}
}
